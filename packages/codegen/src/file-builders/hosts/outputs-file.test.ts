import type { HostOutputsDescription } from "@powerhousedao/host-core";
import { describe, expect, it } from "vitest";
import { z } from "zod";
import {
  buildConfigJsonDeclaration,
  buildHostsTypesDts,
  declaredDependencies,
  withHostsTscScript,
} from "./host-typing-files.js";
import { buildOutputsFiles, buildOutputsTree } from "./outputs-file.js";

function describeOutputs(
  schema: z.ZodType,
  drives: string[],
): HostOutputsDescription {
  const { $schema: _dialect, ...outputsSchema } = z.toJSONSchema(schema, {
    io: "output",
  }) as Record<string, unknown>;
  return {
    host: "switchboard",
    runnerModule: "@powerhousedao/ph-cli/runners/switchboard",
    outputsSchema,
    drives,
    hash: "sha256:00112233",
  };
}

// mirrors the switchboard runner's outputsSchema
const switchboardOutputs = z.strictObject({
  origin: z.url(),
  endpoints: z.strictObject({ graphql: z.url(), mcp: z.url().optional() }),
  drives: z.record(
    z.string(),
    z.strictObject({ id: z.string(), url: z.url() }),
  ),
});

describe("buildOutputsTree", () => {
  it("emits $output leaves, declared drive keys and an $item tree", () => {
    const tree = buildOutputsTree(
      describeOutputs(switchboardOutputs, ["sektar", "workflows"]),
    );
    const out = (path: (string | number)[]) => ({
      $output: { host: "switchboard", path },
    });
    expect(tree.value).toEqual({
      origin: out(["origin"]),
      endpoints: {
        graphql: out(["endpoints", "graphql"]),
        mcp: out(["endpoints", "mcp"]),
      },
      drives: {
        sektar: {
          id: out(["drives", "sektar", "id"]),
          url: out(["drives", "sektar", "url"]),
        },
        workflows: {
          id: out(["drives", "workflows", "id"]),
          url: out(["drives", "workflows", "url"]),
        },
        $item: { id: { $item: ["id"] }, url: { $item: ["url"] } },
      },
    });
    expect(tree.type).toContain('"mcp": OutputToken<string | undefined>');
    expect(tree.type).toContain('"$item": { "id": ItemToken<string>');
  });

  it("gives arrays an $item tree and types enums, numbers and nested collections", () => {
    const tree = buildOutputsTree(
      describeOutputs(
        z.strictObject({
          port: z.number().int(),
          mode: z.enum(["a", "b"]),
          agents: z.array(
            z.strictObject({ name: z.string(), tags: z.array(z.string()) }),
          ),
        }),
        [],
      ),
    );
    expect(tree.value).toMatchObject({
      agents: {
        $item: { name: { $item: ["name"] }, tags: { $item: ["tags"] } },
      },
    });
    expect(tree.type).toContain('"port": OutputToken<number>');
    expect(tree.type).toContain('"mode": OutputToken<"a" | "b">');
    expect(tree.type).toContain('"tags": ItemToken<string[]>');
  });
});

describe("buildOutputsFiles", () => {
  it("writes plain data with the hash export, and a branded .d.ts", () => {
    const { js, dts } = buildOutputsFiles(
      describeOutputs(switchboardOutputs, ["workflows"]),
    );
    expect(js).toMatch(/^\/\/ GENERATED by `ph generate hosts`/);
    expect(js).toContain('export const outputsHash = "sha256:00112233";');
    expect(js).not.toMatch(/^\s*import\b/m);
    expect(dts).toContain(
      'import type { ItemToken, OutputToken } from "@powerhousedao/host-core/schema";',
    );
    expect(dts).toContain(
      'export declare const outputsHash: "sha256:00112233";',
    );
  });
});

describe("host typing files", () => {
  it("references only the declared type-map packages, and declares PHHost with host-core", () => {
    const dts = buildHostsTypesDts(
      declaredDependencies({
        devDependencies: {
          "@powerhousedao/ph-cli": "1",
          "@powerhousedao/host-core": "1",
        },
        peerDependencies: { "@powerhousedao/connect": "1" },
      }),
    );
    expect(dts).toContain(
      'import type {} from "@powerhousedao/ph-cli/runners/switchboard";',
    );
    expect(dts).toContain(
      'import type {} from "@powerhousedao/connect/plugin-configs";',
    );
    expect(dts).not.toContain("@powerhousedao/clint");
    expect(dts).toContain("type PHHost = HostDefinitionByRunner;");
    expect(buildHostsTypesDts(new Set())).not.toContain("PHHost =");
  });

  it("types powerhouse.config.json imports only when shared is declared", () => {
    expect(
      buildConfigJsonDeclaration(new Set(["@powerhousedao/shared"])),
    ).toContain('import("@powerhousedao/shared/clis").PowerhouseConfig');
    expect(buildConfigJsonDeclaration(new Set())).toBeUndefined();
  });

  it("appends tsc -p hosts to the tsc script once", () => {
    expect(withHostsTscScript("tsc")).toBe("tsc && tsc -p hosts");
    expect(withHostsTscScript("tsc && tsc -p hosts")).toBe(
      "tsc && tsc -p hosts",
    );
    expect(withHostsTscScript(undefined)).toBe("tsc -p hosts");
  });
});
