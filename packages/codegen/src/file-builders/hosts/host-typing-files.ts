/**
 * The files that make `tsc -p hosts` check host.js files (typed-host-configs
 * 1.5): `hosts/tsconfig.json` (user-owned once seeded) and `hosts/types.d.ts`
 * (codegen-owned: refreshed by `ph generate hosts`), which pulls the
 * PHHostRunners / PHPluginConfigs augmentations into the program and makes
 * `PHHost` a global type for JSDoc `@satisfies {PHHost}`.
 */

