const SHARED = "@powerhousedao/shared";

/** `powerhouse.config.d.json.ts` (project root): types every
 * `import config from "…/powerhouse.config.json"` as PowerhouseConfig under
 * `allowArbitraryExtensions`. Without it TS infers the JSON's own shape, which
 * widens enum values (`logLevel: "info"` becomes `string`), so a host passing
 * a config block to a runner fails `@satisfies {PHHost}`. Undefined when the
 * project does not declare the shared package. */
export function buildConfigJsonDeclaration(
  dependencies: ReadonlySet<string>,
): string | undefined {
  if (!dependencies.has(SHARED)) return undefined;
  return `// GENERATED by \`ph generate hosts\` (and \`ph init\`). Do not edit.
// Types imports of powerhouse.config.json for \`tsc -p hosts\`
// (allowArbitraryExtensions); the file itself is validated by its JSON Schema.
declare const config: import("${SHARED}/clis").PowerhouseConfig;
export = config;
`;
}

export const CONFIG_JSON_DECLARATION_FILE = "powerhouse.config.d.json.ts";

export const HOSTS_TSC_SCRIPT = "tsc -p hosts";

/** The project's `tsc` script with `tsc -p hosts` appended (idempotent). */
export function withHostsTscScript(script: string | undefined): string {
  if (!script) return HOSTS_TSC_SCRIPT;
  if (script.includes(HOSTS_TSC_SCRIPT)) return script;
  return `${script} && ${HOSTS_TSC_SCRIPT}`;
}
