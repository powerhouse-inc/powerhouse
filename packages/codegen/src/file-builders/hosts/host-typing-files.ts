const HOST_CORE = "@powerhousedao/host-core";

/** Every dependency name a package.json declares (any dependency field). */
export function declaredDependencies(packageJson: unknown): Set<string> {
  const names = new Set<string>();
  if (packageJson === null || typeof packageJson !== "object") return names;
  for (const field of [
    "dependencies",
    "devDependencies",
    "peerDependencies",
    "optionalDependencies",
  ]) {
    const deps = (packageJson as Record<string, unknown>)[field];
    if (deps && typeof deps === "object") {
      for (const name of Object.keys(deps)) names.add(name);
    }
  }
  return names;
}

/** `hosts/types.d.ts` for a project declaring `dependencies`. Only declared
 * packages are referenced: an unresolvable import would fail `tsc -p hosts`,
 * and `ph init` writes this before installing. */
export function buildHostsTypesDts(dependencies: ReadonlySet<string>): string {
  const modules = HOST_TYPE_MAP_MODULES.filter(([pkg]) =>
    dependencies.has(pkg),
  ).flatMap(([, subpaths]) => subpaths);
  const lines = [
    "// GENERATED by `ph generate hosts` (and `ph init`) from this project's",
    "// dependencies. Do not edit; add your own declarations in another file.",
    "// Pulls the runner and plugin packages' PHHostRunners / PHPluginConfigs",
    "// augmentations into `tsc -p hosts`, and declares PHHost globally so a",
    "// host file is typed with `/** @satisfies {PHHost} */` and no import.",
    ...modules.map((specifier) => `import type {} from "${specifier}";`),
  ];
  if (dependencies.has(HOST_CORE)) {
    lines.push(
      `import type { PHHost as HostDefinitionByRunner } from "${HOST_CORE}/schema";`,
      "",
      "declare global {",
      "  /** Any host file, discriminated by `runner.module`. */",
      "  type PHHost = HostDefinitionByRunner;",
      "}",
    );
  }
  lines.push("", "export {};", "");
  return lines.join("\n");
}

