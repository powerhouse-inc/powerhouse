import {
  isSiteId,
  isSiteZone,
  isWellFormedHostname,
  siteWildcard,
} from "./hostnames.js";

/**
 * Renders frpc.toml for one site. Vendored from site-relay
 * (`packages/site-agent/src/render/frpc.ts` at df26ab8), minus the TOML
 * parse-back self-check (no TOML dependency here; the inputs are validated
 * before they are written).
 */
export interface FrpcRenderInput {
  siteId: string;
  siteSecret: string;
  /** The site's zone: `*.<siteZone>` is the wildcard it claims. */
  siteZone: string;
  serverAddr: string;
  serverPort: number;
  serverName: string;
  token: string;
  /** Path of the relay CA file as frpc will read it. */
  trustedCaFile: string;
  /** Hostname/IP of the local Caddy as seen from frpc. */
  caddyHost: string;
  vanityDomains: string[];
}

/** TOML basic strings share JSON's escaping rules for everything we emit. */
function s(value: string): string {
  return JSON.stringify(value);
}

export function renderFrpcToml(input: FrpcRenderInput): string {
  if (!isSiteId(input.siteId))
    throw new Error(`invalid siteId ${input.siteId}`);
  if (!isSiteZone(input.siteZone))
    throw new Error(`invalid siteZone ${input.siteZone}`);
  for (const v of input.vanityDomains) {
    if (!isWellFormedHostname(v) || v.includes("*"))
      throw new Error(`invalid vanity domain ${v}`);
  }
  if (
    !Number.isInteger(input.serverPort) ||
    input.serverPort <= 0 ||
    input.serverPort > 65535
  ) {
    throw new Error(`invalid serverPort ${input.serverPort}`);
  }
  const domains = [siteWildcard(input.siteZone), ...input.vanityDomains];
  const list = `[${domains.map(s).join(", ")}]`;

  return `# Generated by @powerhousedao/portle for site ${input.siteId} (${input.siteZone}). Do not edit; the plugin rewrites it.
serverAddr = ${s(input.serverAddr)}
serverPort = ${input.serverPort}
user = ${s(input.siteId)}
clientID = ${s(input.siteId)}
loginFailExit = false

auth.method = "token"
auth.token = ${s(input.token)}

# Per-site identity, validated by the control plane's frps Login plugin.
metadatas.site_id = ${s(input.siteId)}
metadatas.site_secret = ${s(input.siteSecret)}

# frpc does not verify frps's certificate unless trustedCaFile is set.
transport.tls.enable = true
transport.tls.trustedCaFile = ${s(input.trustedCaFile)}
transport.tls.serverName = ${s(input.serverName)}

webServer.addr = "127.0.0.1"
webServer.port = 7400

log.to = "console"
log.level = "info"

# TLS passthrough (frps routes by SNI, never decrypts); PROXY v2 carries the
# visitor address to Caddy. PROXY protocol only here, never on the http proxy.
[[proxies]]
name = "tls"
type = "https"
localIP = ${s(input.caddyHost)}
localPort = 443
customDomains = ${list}
transport.proxyProtocolVersion = "v2"

# Plain HTTP: Caddy redirects to HTTPS; also carries http-01 for vanity domains.
[[proxies]]
name = "web"
type = "http"
localIP = ${s(input.caddyHost)}
localPort = 80
customDomains = ${list}
`;
}
