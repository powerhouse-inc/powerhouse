import { chromium } from "/home/user/powerhouse/test/package-e2e/node_modules/@playwright/test/index.mjs";
const BASE = process.env.BASE ?? "http://localhost:6607";
const tag = process.env.TAG ?? "dev";
const shot = (p, n) => p.screenshot({ path: `/tmp/connect-eval6/shots/${tag}-${n}.png` });
const browser = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium" });
const ctx = await browser.newContext({ viewport: { width: 1280, height: 860 } });
const page = await ctx.newPage();
const logs = [], bad = [];
page.on("console", (m) => { if (["error", "warning"].includes(m.type()) || /PackageManager|stockroom/i.test(m.text())) logs.push(`[${m.type()}] ${m.text().slice(0, 220)}`); });
page.on("pageerror", (e) => logs.push(`[pageerror] ${String(e).slice(0, 220)}`));
page.on("response", (r) => { if (r.status() >= 400) bad.push(`${r.status()} ${r.url()}`); });
await page.goto(BASE + "/", { waitUntil: "domcontentloaded" });
const rj = page.getByRole("button", { name: "Reject all cookies" });
await rj.waitFor({ timeout: 30000 }).then(() => rj.click()).catch(() => {});
await page.waitForTimeout(8000);
console.log("title:", await page.title(), "| package nav link /stockroom:", await page.locator('a[href="/stockroom"]').count());
await shot(page, "01-home");
// Create a drive with the package's drive app
await page.getByText("Create New Drive").first().click();
await page.waitForTimeout(1500);
const dlg = page.locator('[role="dialog"]').first();
const appSelect = dlg.locator("select");
const opts = await appSelect.locator("option").allInnerTexts().catch(() => []);
console.log("drive app options:", JSON.stringify(opts));
await shot(page, "02-create-drive");
await dlg.getByRole("textbox").first().fill("Runtime Stockroom");
if (opts.some((o) => /stockroom/i.test(o))) await appSelect.selectOption({ label: opts.find((o) => /stockroom/i.test(o)) });
await dlg.getByRole("button", { name: /create/i }).last().click();
await page.waitForTimeout(4000);
const card = page.locator('a[href^="/d/runtime-stockroom"]').first();
const href = await card.getAttribute("href").catch(() => null);
console.log("new drive link:", href);
if (href) { await card.click(); await page.waitForTimeout(5000); }
console.log("drive url:", page.url().replace(BASE, ""));
console.log("drive view text:", (await page.locator("main, body").first().innerText()).replace(/\s+/g, " ").slice(0, 300));
await shot(page, "03-drive-app");
console.log("4xx:\n  " + [...new Set(bad)].join("\n  "));
console.log("logs:\n  " + [...new Set(logs)].slice(0, 15).join("\n  "));
await browser.close();
