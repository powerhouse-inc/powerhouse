import { open, shot, BASE } from "./lib.mjs";
const { browser, page, logs } = await open();
page.on("console", (m) => { if (!["error","warning"].includes(m.type())) logs.push(`[${m.type()}] ${m.text().slice(0, 200)}`); });
await page.goto(BASE + "/inventory", { waitUntil: "domcontentloaded" });
await page.getByTestId("inventory-page").waitFor({ timeout: 90000 });
const reject = page.getByRole("button", { name: "Reject all cookies" });
await reject.waitFor({ timeout: 15000 }).then(() => reject.click()).catch(() => console.log("no banner"));
await page.waitForTimeout(500);
console.log("banner visible:", await reject.isVisible().catch(() => false));
console.log("before:", await page.getByTestId("inventory-summary").innerText());
await page.getByTestId("new-item").click();
await page.getByPlaceholder("Document name").fill("Nuts M6");
await shot(page, "12-modal-filled");
await page.getByRole("button", { name: "Create" }).click();
await page.waitForTimeout(5000);
console.log("url:", page.url());
console.log("after:", await page.getByTestId("inventory-summary").innerText());
console.log("LOGS:\n" + logs.filter(l => !/\[debug\]|Download the React DevTools|vite/.test(l)).slice(-30).join("\n"));
await browser.close();
